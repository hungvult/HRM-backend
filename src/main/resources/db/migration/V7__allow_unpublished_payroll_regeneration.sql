-- Chỉ thêm dữ liệu kiểm soát preview tạo lại; không mở khóa bảng đã công bố.
-- Schema cũ từng để Hibernate tạo bảng này; DB mới cần DDL trước khi ALTER.
CREATE TABLE IF NOT EXISTS payroll_previews (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 token_hash VARCHAR(128) NOT NULL UNIQUE,
 owner_account_id BIGINT NOT NULL REFERENCES accounts(id),
 payroll_year SMALLINT NOT NULL,
 payroll_month SMALLINT NOT NULL,
 input_fingerprint VARCHAR(128) NOT NULL,
 expires_at TIMESTAMPTZ NOT NULL,
 created_payroll_run_id BIGINT REFERENCES payroll_runs(id),
 consumed_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
ALTER TABLE payroll_previews ADD COLUMN regenerate_run_id BIGINT REFERENCES payroll_runs(id);
ALTER TABLE payroll_previews ADD COLUMN expected_revision INTEGER;
ALTER TABLE payroll_runs DROP CONSTRAINT ck_payroll_run_mvp_legacy_fields;
ALTER TABLE payroll_runs ADD CONSTRAINT ck_payroll_run_current_revision
 CHECK (revision >= 1 AND is_current = TRUE AND supersedes_payroll_run_id IS NULL AND superseded_at IS NULL) NOT VALID;
DROP INDEX uq_payroll_mvp_period;
CREATE UNIQUE INDEX uq_payroll_mvp_period ON payroll_runs (payroll_year, payroll_month)
 WHERE status IN ('GENERATED','PUBLISHED') AND is_current = TRUE;
COMMENT ON COLUMN payroll_runs.revision IS 'Tăng sau mỗi lượt tạo lại bảng chưa công bố; snapshot đã công bố giữ nguyên.';
